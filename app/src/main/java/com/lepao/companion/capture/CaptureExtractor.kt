package com.lepao.companion.capture

import com.lepao.companion.core.COMMON_FIELDS
import com.lepao.companion.core.CapturedTokenPair
import com.lepao.companion.core.Endpoints
import com.lepao.companion.core.JsonUtil
import com.lepao.companion.core.Protocol
import com.lepao.companion.core.SessionCookie
import org.json.JSONArray
import org.json.JSONObject
import java.io.UnsupportedEncodingException
import java.net.URLDecoder
import java.nio.charset.StandardCharsets
import java.util.Base64
import javax.crypto.Cipher
import javax.crypto.spec.IvParameterSpec
import javax.crypto.spec.SecretKeySpec

/**
 * Pure-Kotlin extraction of account material from observed `api2.lptiyu.com` traffic.
 *
 * Nothing in this object touches Android, so every rule below is exercised by JVM unit tests with
 * requests generated by [Protocol.buildRequest] (the same encoder the companion uses on the wire).
 */
object CaptureExtractor {

    private const val API_MARKER = "/v3/api.php/"
    private const val PARAMS_PROFILE = "PARAMS_NEW_GAME"
    private const val LOGIN_PROFILE = "NEW_GAME"

    private val DYNAMIC_NAME = Regex("lp[a-z0-9]{2}")
    private val LOGIN_HINTS = listOf("RefreshToken", "quickLogin", "LoginV14")

    private const val MAX_TOKEN_SEARCH_DEPTH = 6

    /** Tail of a captured path: `/v3/api.php/Run2/beforeRunV260?x=1` -> `Run2/beforeRunV260`. */
    fun endpointOf(path: String): String {
        val withoutQuery = path.substringBefore('?').substringBefore('#')
        val marker = withoutQuery.indexOf(API_MARKER)
        val tail = if (marker >= 0) withoutQuery.substring(marker + API_MARKER.length) else withoutQuery
        return tail.trim('/')
    }

    fun parseFormBody(text: String): LinkedHashMap<String, String> {
        val result = LinkedHashMap<String, String>()
        if (text.isBlank()) return result
        for (pair in text.split('&')) {
            if (pair.isEmpty()) continue
            val separator = pair.indexOf('=')
            if (separator < 0) {
                result[urlDecode(pair)] = ""
                continue
            }
            result[urlDecode(pair.substring(0, separator))] = urlDecode(pair.substring(separator + 1))
        }
        return result
    }

    /** Decrypts a `key=<ciphertext>` request body; null when the body carries no decryptable key. */
    fun decryptParams(form: Map<String, String>): LinkedHashMap<String, String>? {
        val ciphertext = form["key"] ?: return null
        val plaintext = try {
            Protocol.decryptText(ciphertext, PARAMS_PROFILE)
        } catch (_: Exception) {
            return null
        }
        val json = JsonUtil.parseObjectOrNull(plaintext) ?: return null
        val result = LinkedHashMap<String, String>()
        val keys = json.keys()
        while (keys.hasNext()) {
            val key = keys.next()
            val value = json.opt(key)
            result[key] = when (value) {
                null, JSONObject.NULL -> ""
                is String -> value
                else -> value.toString()
            }
        }
        return result
    }

    /** A request is an authenticated context candidate when every common wire field is present. */
    fun hasIdentityFields(params: Map<String, String>): Boolean =
        COMMON_FIELDS.all { params[it]?.isNotBlank() == true }

    fun identityOf(params: Map<String, String>): LinkedHashMap<String, String> {
        val result = LinkedHashMap<String, String>()
        for (key in COMMON_FIELDS) result[key] = params[key] ?: ""
        return result
    }

    fun dynamicFieldName(params: Map<String, String>): String? =
        params.keys.firstOrNull { DYNAMIC_NAME.matches(it) }

    /**
     * Decrypts the device dynamic field. Its plaintext is `umid + md5(timestamp)`, so the suffix is
     * verified against the request timestamp before the prefix is accepted as the UMID.
     */
    fun decodeUmid(dynamicValue: String, timestamp: String): String? {
        if (timestamp.length != 10 || !timestamp.all { it.isDigit() }) return null
        val compact = dynamicValue.filterNot { it.isWhitespace() }
        if (compact.isEmpty()) return null
        val index = (timestamp.toLong() % Protocol.DYNAMIC_KEYS.size).toInt()
        val (key, iv) = Protocol.DYNAMIC_KEYS[index]
        val plaintext = try {
            val raw = Base64.getDecoder().decode(compact)
            val cipher = Cipher.getInstance("AES/CBC/PKCS5Padding")
            cipher.init(
                Cipher.DECRYPT_MODE,
                SecretKeySpec(key.toByteArray(StandardCharsets.US_ASCII), "AES"),
                IvParameterSpec(iv.toByteArray(StandardCharsets.US_ASCII)),
            )
            String(cipher.doFinal(raw), StandardCharsets.UTF_8)
        } catch (_: Exception) {
            return null
        }
        val suffix = Protocol.md5Hex(timestamp)
        if (!plaintext.endsWith(suffix) || plaintext.length <= suffix.length) return null
        return plaintext.dropLast(suffix.length)
    }

    /**
     * UMID for one observed request. `Run/stopRunV278` reuses the dynamic field name for the formal
     * start's `str` value, so it can never be a UMID source.
     */
    fun umidFromRequest(endpoint: String, params: Map<String, String>): String? {
        if (endpoint == Endpoints.STOP || endpoint.endsWith("stopRunV278")) return null
        val timestamp = params["timestamp"] ?: return null
        val name = dynamicFieldName(params) ?: return null
        val value = params[name] ?: return null
        return decodeUmid(value, timestamp)
    }

    /** `oaid`/`mac` are only trustworthy when the official app submitted a run result. */
    fun deviceFieldsFrom(endpoint: String, params: Map<String, String>): Map<String, String> {
        if (endpoint != Endpoints.STOP && !endpoint.endsWith("stopRunV278")) return emptyMap()
        val result = LinkedHashMap<String, String>()
        for (key in listOf("oaid", "mac")) {
            val value = params[key]
            if (!value.isNullOrBlank()) result[key] = value
        }
        return result
    }

    fun isLoginEndpoint(endpoint: String): Boolean =
        LOGIN_HINTS.any { endpoint.contains(it, ignoreCase = true) }

    /**
     * Extracts a token pair from a login/refresh response.
     *
     * `data` may be an AES ciphertext string or an object. Both access and refresh tokens must be
     * present; a plain `token` alias is accepted only when `access_token` is missing.
     */
    fun extractTokenPair(
        endpoint: String,
        statusCode: Int,
        responseBody: String,
        capturedAt: Long,
    ): CapturedTokenPair? {
        if (statusCode != 200) return null
        if (!isLoginEndpoint(endpoint)) return null
        val envelope = JsonUtil.parseObjectOrNull(responseBody) ?: return null
        val status = envelope.opt("status")
        val statusOk = (status is Number && status.toInt() == 1) ||
            (status is String && status.trim() == "1")
        if (!statusOk) return null

        val found = LinkedHashMap<String, String>()
        collectTokens(envelope, found, 0)
        val access = found["access_token"] ?: found["token"] ?: return null
        val refresh = found["refresh_token"] ?: return null
        if (access.isBlank() || refresh.isBlank()) return null
        val uid = found["uid"]?.takeIf { it.isNotBlank() }
        val decoded = decodedData(envelope)
        val expire = JsonUtil.optLongOrNull(envelope, "refresh_expire")
            ?: decoded?.let { JsonUtil.optLongOrNull(it, "refresh_expire") }
        return CapturedTokenPair(
            accessToken = access,
            refreshToken = refresh,
            refreshExpire = expire,
            uid = uid,
            endpoint = endpoint,
            capturedAt = capturedAt,
        )
    }

    private fun decodedData(envelope: JSONObject): JSONObject? {
        val data = envelope.opt("data")
        if (data is JSONObject) return data
        if (data !is String || data.isEmpty()) return null
        return try {
            JsonUtil.parseObjectOrNull(Protocol.decryptText(data, LOGIN_PROFILE))
        } catch (_: Exception) {
            null
        }
    }

    /**
     * Depth-first collection of the first value seen for each key of interest. The envelope level is
     * included so both `{"data":{...}}` and decrypted `data` strings are covered.
     */
    private fun collectTokens(node: Any?, target: MutableMap<String, String>, depth: Int) {
        if (depth > MAX_TOKEN_SEARCH_DEPTH) return
        when (node) {
            is JSONObject -> {
                val keys = node.keys()
                while (keys.hasNext()) {
                    val key = keys.next()
                    val value = node.opt(key)
                    if (key == "data" && value is String) {
                        val decoded = try {
                            JsonUtil.parseObjectOrNull(Protocol.decryptText(value, LOGIN_PROFILE))
                        } catch (_: Exception) {
                            null
                        }
                        if (decoded != null) {
                            collectTokens(decoded, target, depth + 1)
                            continue
                        }
                    }
                    if (value is JSONObject || value is JSONArray) {
                        collectTokens(value, target, depth + 1)
                        continue
                    }
                    if (TARGET_KEYS.contains(key)) {
                        val text = when (value) {
                            null, JSONObject.NULL -> null
                            is String -> value
                            is Number -> value.toString()
                            else -> null
                        }
                        if (!text.isNullOrBlank() && !target.containsKey(key)) target[key] = text
                    }
                }
            }
            is JSONArray -> {
                for (index in 0 until node.length()) {
                    val value = node.opt(index)
                    if (value is JSONObject || value is JSONArray) collectTokens(value, target, depth + 1)
                }
            }
        }
    }

    private val TARGET_KEYS = listOf("access_token", "refresh_token", "token", "uid")

    fun parseCookieHeader(value: String): List<SessionCookie> {
        val result = ArrayList<SessionCookie>()
        for (part in value.split(';')) {
            val trimmed = part.trim()
            if (trimmed.isEmpty()) continue
            val separator = trimmed.indexOf('=')
            if (separator <= 0) continue
            val name = trimmed.substring(0, separator).trim()
            val cookieValue = trimmed.substring(separator + 1).trim()
            if (name.isEmpty()) continue
            result.add(SessionCookie(name, cookieValue))
        }
        return result
    }

    fun parseSetCookie(value: String): SessionCookie? {
        val parts = value.split(';')
        if (parts.isEmpty()) return null
        val pair = parts.first().trim()
        val separator = pair.indexOf('=')
        if (separator <= 0) return null
        val name = pair.substring(0, separator).trim()
        val cookieValue = pair.substring(separator + 1).trim()
        if (name.isEmpty()) return null
        var domain = "api2.lptiyu.com"
        var path = "/"
        var secure = true
        var expires: Long? = null
        for (attribute in parts.drop(1)) {
            val trimmed = attribute.trim()
            val eq = trimmed.indexOf('=')
            val key = (if (eq >= 0) trimmed.substring(0, eq) else trimmed).trim().lowercase()
            val attributeValue = if (eq >= 0) trimmed.substring(eq + 1).trim() else ""
            when (key) {
                "path" -> if (attributeValue.isNotEmpty()) path = attributeValue
                "domain" -> if (attributeValue.isNotEmpty()) domain = attributeValue.trimStart('.')
                "secure" -> secure = true
                "max-age" -> attributeValue.toLongOrNull()?.let {
                    expires = System.currentTimeMillis() / 1000 + it
                }
                "expires" -> {
                    val parsed = parseHttpDate(attributeValue)
                    if (parsed != null) expires = parsed
                }
            }
        }
        return SessionCookie(name, cookieValue, domain, path, secure, expires)
    }

    private fun parseHttpDate(value: String): Long? = try {
        java.time.ZonedDateTime.parse(value, java.time.format.DateTimeFormatter.RFC_1123_DATE_TIME)
            .toEpochSecond()
    } catch (_: Exception) {
        null
    }

    private fun urlDecode(text: String): String = try {
        URLDecoder.decode(text, "UTF-8")
    } catch (_: UnsupportedEncodingException) {
        text
    } catch (_: IllegalArgumentException) {
        text
    }
}
